class SubscriptionPdfGenerator {
  static Future<Uint8List> generate(SubscriptionModel model) async {
    await _Pdf.loadFonts();
    final pdf = pw.Document();

    final currency = NumberFormat.currency(
      locale: 'en_IN',
      symbol: AppConfig.currencySymbol,
    );
    String fmt(num v) => currency.format(v);
    String fmtDate(DateTime? d) => d == null ? '-' : DateFormat('dd MMM yyyy, hh:mm a').format(d);

    pw.Widget section(String title, List<pw.Widget> children) => pw.Container(
          margin: const pw.EdgeInsets.only(bottom: 14),
          padding: const pw.EdgeInsets.all(14),
          decoration: pw.BoxDecoration(
            border: pw.Border.all(color: PdfColors.grey300),
            borderRadius: pw.BorderRadius.circular(8),
          ),
          child: pw.Column(
            crossAxisAlignment: pw.CrossAxisAlignment.start,
            children: [
              pw.Padding(
                padding: const pw.EdgeInsets.only(bottom: 8),
                child: pw.Text(
                  title,
                  style: _Pdf.style(size: 13, color: _pdfBrand, isBold: true),
                ),
              ),
              ...children,
            ],
          ),
        );

    final products = model.products;

    pdf.addPage(
      pw.MultiPage(
        margin: const pw.EdgeInsets.all(24),
        theme: pw.ThemeData.withFont(base: _Pdf.base, bold: _Pdf.bold),
        footer: _Pdf.footer,
        build: (ctx) => [
          // ── HEADER ──────────────────────────────────────────────────
          pw.Container(
            padding: const pw.EdgeInsets.all(20),
            decoration: pw.BoxDecoration(
              color: _pdfBrandLight,
              borderRadius: pw.BorderRadius.circular(10),
            ),
            child: pw.Row(
              mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
              children: [
                pw.Column(
                  crossAxisAlignment: pw.CrossAxisAlignment.start,
                  children: [
                    pw.Text(
                      'SUBSCRIPTION REPORT',
                      style: _Pdf.style(size: 22, color: _pdfBrand, isBold: true),
                    ),
                    pw.SizedBox(height: 4),
                    pw.Text(AppConfig.appName, style: _Pdf.style(size: 11, color: _pdfBrand)),
                    pw.SizedBox(height: 2),
                    pw.Text('ID: ${model.id ?? '-'}', style: _Pdf.style(size: 10)),
                  ],
                ),
                pw.Container(
                  padding: const pw.EdgeInsets.symmetric(horizontal: 14, vertical: 8),
                  decoration: pw.BoxDecoration(
                    color: PdfColors.white,
                    borderRadius: pw.BorderRadius.circular(8),
                  ),
                  child: pw.Text(
                    model.status.toUpperCase(),
                    style: _Pdf.style(size: 12, color: _pdfBrand, isBold: true),
                  ),
                ),
              ],
            ),
          ),

          pw.SizedBox(height: 20),

          section('Subscription Details', [
            _Pdf.infoRow('Subscription ID', model.id ?? '-'),
            _Pdf.infoRow('User ID', model.userId),
            _Pdf.infoRow('Warehouse ID', model.warehouseId),
            _Pdf.infoRow('Status', model.status),
            _Pdf.infoRow('Pause Reason', model.pauseReason),
            _Pdf.infoRow('Created At', fmtDate(model.createdAt)),
            _Pdf.infoRow('Updated At', fmtDate(model.updatedAt)),
            _Pdf.infoRow('Next Delivery', fmtDate(model.nextDeliveryAt)),
            _Pdf.infoRow('Last Order ID', model.lastOrderId ?? '-'),
          ]),

          section('Customer Details', [
            _Pdf.infoRow('Name', model.user.userName),
            _Pdf.infoRow('Email', model.user.email),
            _Pdf.infoRow('Phone', model.user.mobileNo),
          ]),

          section('Delivery Address', [
            _Pdf.infoRow('Name', model.deliveryAddress.name),
            _Pdf.infoRow('Address', model.deliveryAddress.address),
            _Pdf.infoRow('Locality', model.deliveryAddress.locality),
            _Pdf.infoRow('Sub Locality', model.deliveryAddress.subLocality),
            _Pdf.infoRow('District', model.deliveryAddress.district),
            _Pdf.infoRow('City', model.deliveryAddress.city),
            _Pdf.infoRow('State', model.deliveryAddress.state),
            _Pdf.infoRow('Pincode', model.deliveryAddress.pinCode),
            _Pdf.infoRow('Country', model.deliveryAddress.country),
            _Pdf.infoRow(
              'Coordinates',
              '${model.deliveryAddress.latitude.toStringAsFixed(6)}, ${model.deliveryAddress.longitude.toStringAsFixed(6)}',
            ),
          ]),

          section('Repeat Schedule', [
            _Pdf.infoRow('Frequency', model.repeatSchedule.frequency.name),
            _Pdf.infoRow('Schedule', model.repeatSchedule.displayString),
            _Pdf.infoRow(
              'Time',
              '${model.repeatSchedule.timeSlot.hour}:${model.repeatSchedule.timeSlot.minute.toString().padLeft(2, '0')}',
            ),
          ]),

          // ── PRODUCTS TABLE ───────────────────────────────────────────
          _Pdf.sectionTitle('Products'),
          pw.Table(
            border: pw.TableBorder.all(color: PdfColors.grey300, width: 0.6),
            columnWidths: {
              0: const pw.FlexColumnWidth(2.2),
              1: const pw.FlexColumnWidth(1.5),
              2: const pw.FlexColumnWidth(1.3),
              3: const pw.FlexColumnWidth(1.3),
              4: const pw.FlexColumnWidth(1.1),
              5: const pw.FlexColumnWidth(1.3),
              6: const pw.FlexColumnWidth(1.3),
            },
            children: [
              pw.TableRow(
                decoration: pw.BoxDecoration(color: _pdfBrandLight),
                children: [
                  _Pdf.tableHeaderCell('Product'),
                  _Pdf.tableHeaderCell('Brand / SKU'),
                  _Pdf.tableHeaderCell('Pack Size'),
                  _Pdf.tableHeaderCell('MRP'),
                  _Pdf.tableHeaderCell('Price'),
                  _Pdf.tableHeaderCell('Qty'),
                  _Pdf.tableHeaderCell('Total'),
                ],
              ),
              ...products.map((product) {
                final detailEntry = model.productDetails.entries.firstWhere(
                  (e) => e.key.startsWith(product.id ?? ''),
                  orElse: () => MapEntry(
                    '',
                    OrderProductDetail(
                      packVariantId: '',
                      packSize: 0,
                      pricePerPack: 0,
                      quantity: 0,
                      finalAmount: 0,
                      mrpPerPack: 0,
                    ),
                  ),
                );
                final d = detailEntry.value;
                return pw.TableRow(children: [
                  _Pdf.tableCell(product.name),
                  _Pdf.tableCell('${product.brandName}\n${product.sku}'),
                  _Pdf.tableCellRight('${d.packSize} pcs'),
                  _Pdf.tableCellRight(fmt(d.mrpPerPack ?? 0)),
                  _Pdf.tableCellRight(fmt(d.pricePerPack)),
                  _Pdf.tableCellRight(d.quantity.toString()),
                  _Pdf.tableCellRight(fmt(d.finalAmount)),
                ]);
              }),
            ],
          ),

          pw.SizedBox(height: 20),

          section('Financial Summary', [
            _Pdf.infoRow('Subtotal', fmt(model.subtotal)),
            _Pdf.infoRow('Discount', '- ${fmt(model.discount)}'),
            _Pdf.infoRow('Applied Coupon', model.appliedCouponCode ?? '-'),
            _Pdf.infoRow('Delivery Charge', fmt(model.deliveryCharge)),
            _Pdf.infoRow('Total', fmt(model.total)),
          ]),

          section('Delivery Config', [
            _Pdf.infoRow('Type', model.deliveryConfig.deliveryTypeApplied),
            _Pdf.infoRow('Base Charge', fmt(model.deliveryConfig.baseDeliveryCharge)),
            _Pdf.infoRow('Per KM', fmt(model.deliveryConfig.deliveryChargePerKm)),
            _Pdf.infoRow('Fixed Charge', fmt(model.deliveryConfig.fixedDeliveryCharge)),
            _Pdf.infoRow('Fixed KM Charge', fmt(model.deliveryConfig.fixedDeliveryChargeForKm)),
            _Pdf.infoRow('Free Delivery Threshold', fmt(model.deliveryConfig.freeDeliveryThreshold)),
            _Pdf.infoRow('Free Delivery Days', model.deliveryConfig.freeDeliveryDays.toString()),
          ]),

          section('Delivery Boy Config', [
            _Pdf.infoRow('Base Charge', fmt(model.deliveryBoyConfig.baseDeliveryCharge)),
            _Pdf.infoRow('Delivery Charge', fmt(model.deliveryBoyConfig.deliveryCharge)),
            _Pdf.infoRow('Per KM', fmt(model.deliveryBoyConfig.deliveryChargePerKm)),
            _Pdf.infoRow('Fixed Charge', fmt(model.deliveryBoyConfig.fixedDeliveryCharge)),
            _Pdf.infoRow('Fixed KM Charge', fmt(model.deliveryBoyConfig.fixedDeliveryChargeForKm)),
            _Pdf.infoRow('Estimated Payout', fmt(model.deliveryBoyConfig.estimatedDeliveryBoyPayout)),
          ]),

          section('Tax Configuration', [
            _Pdf.infoRow('GST', '${model.taxConfig.gstPercentage}%'),
            _Pdf.infoRow('Packing Fee', fmt(model.taxConfig.handlingCharge)),
            _Pdf.infoRow('Platform Charge', fmt(model.taxConfig.platformCharge)),
            _Pdf.infoRow('Payment Gateway', '${model.taxConfig.paymentGatewayChargePercentage}%'),
          ]),
        ],
      ),
    );

    return pdf.save();
  }

  static Future<void> printPdf(SubscriptionModel model) async {
    final data = await generate(model);
    await Printing.layoutPdf(
      onLayout: (_) async => data,
      name: 'subscription_${model.id}.pdf',
    );
  }
}
