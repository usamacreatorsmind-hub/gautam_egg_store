// ---------------------------------------------------------------------------
// Brand color bridge — derives PDF colors from AppColors so every client
// automatically gets the right brand in their printed bills.
// ---------------------------------------------------------------------------
PdfColor _toPdf(Color c) => PdfColor(c.r, c.g, c.b);

final _pdfBrand = _toPdf(AppColors.brandSeed);
final _pdfBrandLight = _toPdf(AppColors.infoLight);
final _pdfSuccess = _toPdf(AppColors.success);
final _pdfWarning = _toPdf(AppColors.warning);
final _pdfError = _toPdf(AppColors.error);

// ---------------------------------------------------------------------------
// Shared helpers
// ---------------------------------------------------------------------------
class _Pdf {
  static late pw.Font base;
  static late pw.Font bold;

  static Future<void> loadFonts() async {
    base = await PdfGoogleFonts.poppinsRegular();
    bold = await PdfGoogleFonts.poppinsBold();
  }

  static pw.TextStyle style({
    double size = 10,
    PdfColor? color,
    bool isBold = false,
  }) =>
      pw.TextStyle(
        font: isBold ? bold : base,
        fontSize: size,
        color: color,
      );

  static pw.Widget sectionTitle(String title) => pw.Padding(
        padding: const pw.EdgeInsets.only(top: 14, bottom: 6),
        child: pw.Row(
          children: [
            pw.Container(
              width: 3,
              height: 14,
              color: _pdfBrand,
              margin: const pw.EdgeInsets.only(right: 6),
            ),
            pw.Text(title, style: style(size: 13, color: _pdfBrand, isBold: true)),
          ],
        ),
      );

  static pw.Widget infoRow(String label, String value) => pw.Padding(
        padding: const pw.EdgeInsets.symmetric(vertical: 2.5),
        child: pw.Row(
          crossAxisAlignment: pw.CrossAxisAlignment.start,
          children: [
            pw.SizedBox(
              width: 150,
              child: pw.Text(label, style: style(isBold: true)),
            ),
            pw.Expanded(child: pw.Text(value, style: style())),
          ],
        ),
      );

  static pw.Widget divider() => pw.Divider(color: PdfColors.grey300, height: 1);

  static pw.Widget summaryRow(String label, String value, {bool isBold = false, PdfColor? valueColor}) => pw.Padding(
        padding: const pw.EdgeInsets.symmetric(vertical: 3),
        child: pw.Row(
          mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
          children: [
            pw.Text(label, style: style(isBold: isBold)),
            pw.Text(value, style: style(isBold: isBold, color: valueColor)),
          ],
        ),
      );

  static pw.Widget tableHeaderCell(String text) => pw.Container(
        padding: const pw.EdgeInsets.all(6),
        child: pw.Text(text, style: style(size: 9, isBold: true)),
      );

  static pw.Widget tableCell(String text, {pw.Alignment? align}) => pw.Container(
        padding: const pw.EdgeInsets.all(6),
        alignment: align,
        child: pw.Text(text, style: style(size: 9)),
      );

  static pw.Widget tableCellRight(String text) => tableCell(text, align: pw.Alignment.centerRight);

  static pw.Widget footer(pw.Context ctx) => pw.Column(
        children: [
          divider(),
          pw.SizedBox(height: 4),
          pw.Row(
            mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
            children: [
              pw.Text(
                'Generated by ${AppConfig.appName} · ${DateFormat('dd MMM yyyy').format(DateTime.now())}',
                style: style(size: 7, color: PdfColors.grey600),
              ),
              pw.Text(
                'Page ${ctx.pageNumber} of ${ctx.pagesCount}',
                style: style(size: 7, color: PdfColors.grey600),
              ),
            ],
          ),
        ],
      );
}

// ---------------------------------------------------------------------------
// ORDER BILL  (customer-facing)
// ---------------------------------------------------------------------------
class OrderBillGenerator {
  static Future<Uint8List> generate(OrderModel order) async {
    await _Pdf.loadFonts();
    final pdf = pw.Document();

    final currency = NumberFormat.currency(
      locale: 'en_IN',
      symbol: AppConfig.currencySymbol,
      decimalDigits: 2,
    );
    final dateFormat = DateFormat('dd MMM yyyy, hh:mm a');
    String fmt(num v) => currency.format(v);

    // Reconstruct financial components
    double totalMrp = 0;
    double totalSellingPrice = 0;
    for (var detail in order.productDetails.values) {
      final mrp = detail.mrpPerPack ?? detail.pricePerPack;
      totalMrp += mrp * detail.quantity;
      totalSellingPrice += detail.pricePerPack * detail.quantity;
    }

    final mrpDiscount = (totalMrp - totalSellingPrice).clamp(0.0, double.infinity);
    final couponDiscount = (order.discount - mrpDiscount).clamp(0.0, double.infinity);
    final netProductAmount = (totalSellingPrice - couponDiscount).clamp(0.0, double.infinity);

    final platformFee = order.platformFee;
    final packingFee = order.packingFee;
    final extraOrderCharge = order.extraOrderCharge;

    final baseTotal = netProductAmount + order.deliveryCharge + platformFee + packingFee + extraOrderCharge;

    const gstAmount = 0.0;

    final gatewayFee = (order.paymentMethod != null &&
            order.paymentMethod!.toLowerCase() != 'cod' &&
            order.paymentMethod!.toLowerCase() != 'cash on delivery')
        ? baseTotal * order.taxConfig.paymentGatewayChargePercentage / 100
        : 0.0;

    final statusColor = order.status.toLowerCase() == 'delivered'
        ? _pdfSuccess
        : order.status.toLowerCase() == 'cancelled'
            ? _pdfError
            : _pdfWarning;

    pdf.addPage(
      pw.MultiPage(
        margin: const pw.EdgeInsets.all(28),
        pageFormat: PdfPageFormat.a4,
        theme: pw.ThemeData.withFont(base: _Pdf.base, bold: _Pdf.bold),
        footer: _Pdf.footer,
        build: (ctx) => [
          // ── HEADER ──────────────────────────────────────────────────
          pw.Container(
            padding: const pw.EdgeInsets.all(20),
            decoration: pw.BoxDecoration(
              color: _pdfBrand,
              borderRadius: pw.BorderRadius.circular(10),
            ),
            child: pw.Row(
              mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
              crossAxisAlignment: pw.CrossAxisAlignment.start,
              children: [
                pw.Column(
                  crossAxisAlignment: pw.CrossAxisAlignment.start,
                  children: [
                    pw.Text(
                      'ORDER BILL',
                      style: _Pdf.style(size: 22, color: PdfColors.white, isBold: true),
                    ),
                    pw.SizedBox(height: 4),
                    pw.Text(
                      AppConfig.legalCompanyName,
                      style: _Pdf.style(size: 11, color: PdfColors.white),
                    ),
                    pw.SizedBox(height: 2),
                    pw.Text(
                      '${AppConfig.supportEmail}  ·  ${AppConfig.supportPhone}',
                      style: _Pdf.style(size: 9, color: PdfColors.white),
                    ),
                  ],
                ),
                pw.Column(
                  crossAxisAlignment: pw.CrossAxisAlignment.end,
                  children: [
                    pw.Container(
                      padding: const pw.EdgeInsets.symmetric(horizontal: 12, vertical: 6),
                      decoration: pw.BoxDecoration(
                        color: PdfColors.white,
                        borderRadius: pw.BorderRadius.circular(6),
                      ),
                      child: pw.Text(
                        order.status.toUpperCase(),
                        style: _Pdf.style(size: 11, color: statusColor, isBold: true),
                      ),
                    ),
                    pw.SizedBox(height: 8),
                    pw.Text(
                      'Order #${order.orderNumber}',
                      style: _Pdf.style(size: 10, color: PdfColors.white, isBold: true),
                    ),
                    pw.Text(
                      dateFormat.format(order.createdAt),
                      style: _Pdf.style(size: 9, color: PdfColors.white),
                    ),
                  ],
                ),
              ],
            ),
          ),

          pw.SizedBox(height: 18),

          // ── ORDER DETAILS ────────────────────────────────────────────
          _Pdf.sectionTitle('Order Details'),
          _Pdf.infoRow('Order Number', order.orderNumber),
          _Pdf.infoRow('Date', dateFormat.format(order.createdAt)),
          _Pdf.infoRow('Payment Method', order.paymentMethod ?? '-'),
          _Pdf.infoRow('Payment Status', order.paymentStatus ?? '-'),
          if (order.appliedCouponCode != null && order.appliedCouponCode!.isNotEmpty)
            _Pdf.infoRow('Coupon Applied', order.appliedCouponCode!),
          if (order.notes != null && order.notes!.isNotEmpty) _Pdf.infoRow('Notes', order.notes!),

          // ── CUSTOMER ─────────────────────────────────────────────────
          _Pdf.sectionTitle('Customer'),
          _Pdf.infoRow('Name', order.user.userName),
          _Pdf.infoRow('Phone', order.user.mobileNo),

          // ── DELIVERY ADDRESS ─────────────────────────────────────────
          _Pdf.sectionTitle('Delivery Address'),
          _Pdf.infoRow('Contact', '${order.deliveryAddress.name}  ·  ${order.deliveryAddress.phone}'),
          _Pdf.infoRow(
              'Address',
              [
                order.deliveryAddress.address,
                order.deliveryAddress.locality,
                if (order.deliveryAddress.subLocality.isNotEmpty) order.deliveryAddress.subLocality,
                order.deliveryAddress.city,
                order.deliveryAddress.state,
                order.deliveryAddress.pinCode,
              ].where((s) => s.isNotEmpty).join(', ')),

          // ── PRODUCTS ─────────────────────────────────────────────────
          _Pdf.sectionTitle('Products'),
          pw.Table(
            border: pw.TableBorder.all(color: PdfColors.grey300, width: 0.5),
            columnWidths: {
              0: const pw.FlexColumnWidth(3.0),
              1: const pw.FlexColumnWidth(1.2),
              2: const pw.FlexColumnWidth(1.3),
              3: const pw.FlexColumnWidth(1.3),
              4: const pw.FlexColumnWidth(0.8),
              5: const pw.FlexColumnWidth(1.4),
            },
            children: [
              pw.TableRow(
                decoration: pw.BoxDecoration(color: _pdfBrandLight),
                children: [
                  _Pdf.tableHeaderCell('Product'),
                  _Pdf.tableHeaderCell('Pack Size'),
                  _Pdf.tableHeaderCell('MRP'),
                  _Pdf.tableHeaderCell('Price'),
                  _Pdf.tableHeaderCell('Qty'),
                  _Pdf.tableHeaderCell('Total'),
                ],
              ),
              ...order.products.map((product) {
                final detail = order.productDetails.values.firstWhere(
                  (e) => e.packVariantId.contains(product.id ?? ''),
                  orElse: () => OrderProductDetail(
                    packVariantId: '',
                    packSize: 1,
                    pricePerPack: 0,
                    quantity: 0,
                    finalAmount: 0,
                  ),
                );

                // Try to get the variant name/unit if detail doesn't have it
                final String productDisplayName = detail.unit.isNotEmpty ? '${product.name} (${detail.unit})' : product.name;

                return pw.TableRow(
                  children: [
                    _Pdf.tableCell(productDisplayName),
                    _Pdf.tableCellRight('${detail.packSize} pcs'),
                    _Pdf.tableCellRight(fmt(detail.mrpPerPack ?? 0)),
                    _Pdf.tableCellRight(fmt(detail.pricePerPack)),
                    _Pdf.tableCellRight(detail.quantity.toString()),
                    _Pdf.tableCellRight(fmt(detail.finalAmount)),
                  ],
                );
              }),
            ],
          ),

          pw.SizedBox(height: 20),

          // ── BILL SUMMARY ─────────────────────────────────────────────
          _Pdf.sectionTitle('Bill Summary'),
          pw.Container(
            padding: const pw.EdgeInsets.all(14),
            decoration: pw.BoxDecoration(
              color: PdfColors.grey100,
              borderRadius: pw.BorderRadius.circular(8),
            ),
            child: pw.Column(
              children: [
                _Pdf.summaryRow('Items Total (MRP)', fmt(totalMrp)),
                if (mrpDiscount > 0) _Pdf.summaryRow('Product Discount', '- ${fmt(mrpDiscount)}', valueColor: _pdfSuccess),
                if (couponDiscount > 0)
                  _Pdf.summaryRow(
                    'Coupon (${order.appliedCouponCode ?? 'Savings'})',
                    '- ${fmt(couponDiscount)}',
                    valueColor: _pdfSuccess,
                  ),
                pw.SizedBox(height: 4),
                _Pdf.summaryRow('Items Subtotal', fmt(totalSellingPrice - couponDiscount), isBold: true),
                pw.SizedBox(height: 4),
                _Pdf.divider(),
                pw.SizedBox(height: 4),
                _Pdf.summaryRow('Delivery Charge', fmt(order.deliveryCharge)),
                if (platformFee > 0) _Pdf.summaryRow('Platform Fee', fmt(platformFee)),
                if (packingFee > 0) _Pdf.summaryRow('Packing Fee', fmt(packingFee)),
                if (extraOrderCharge > 0) _Pdf.summaryRow('Extra Order Charge', fmt(extraOrderCharge)),
                if (gatewayFee > 0) _Pdf.summaryRow('Payment Gateway Fee', fmt(gatewayFee)),
                pw.SizedBox(height: 4),
                _Pdf.divider(),
                pw.SizedBox(height: 4),
                _Pdf.summaryRow(
                  'TOTAL',
                  fmt(order.computedTotal),
                  isBold: true,
                  valueColor: _pdfBrand,
                ),
              ],
            ),
          ),

          pw.SizedBox(height: 24),

          // ── THANK YOU ────────────────────────────────────────────────
          pw.Center(
            child: pw.Column(
              children: [
                pw.Text(
                  'Thank you for shopping with ${AppConfig.appName}!',
                  style: _Pdf.style(size: 11, color: _pdfBrand, isBold: true),
                ),
                pw.SizedBox(height: 4),
                pw.Text(
                  '${AppConfig.supportEmail}  ·  ${AppConfig.supportPhone}',
                  style: _Pdf.style(size: 9, color: PdfColors.grey600),
                ),
              ],
            ),
          ),
        ],
      ),
    );

    return pdf.save();
  }

  static Future<File> savePdf(OrderModel order) async {
    final bytes = await generate(order);
    final dir = await getTemporaryDirectory();
    final file = File('${dir.path}/${order.orderNumber}.pdf');
    await file.writeAsBytes(bytes);
    return file;
  }

  static Future<void> printPdf(OrderModel order) async {
    final bytes = await generate(order);
    await Printing.layoutPdf(onLayout: (_) async => bytes);
  }
}

